let currentLang = "ja";

function t(key) {
  const keys = key.split(".");
  let value = translations[currentLang];
  for (const k of keys) {
    if (value === undefined) return key;
    value = value[k];
  }
  return value || key;
}

function setLang(lang) {
  currentLang = lang;
}

function getLang() {
  return currentLang;
}

function toggleLang() {
  currentLang = currentLang === "ja" ? "en" : "ja";
  return currentLang;
}
